import assert from 'node:assert/strict';
import { WorkspaceStore, createWorkspace, dateOffset, validateWorkspace } from './dist/js/WorkspaceStore.js';
const personal = new WorkspaceStore(createWorkspace(false));
const demo = new WorkspaceStore(createWorkspace(true));
assert.equal(personal.data.projects.length, 0);
assert.equal(demo.data.projects.length, 3);
const before = demo.data.cards.length;
const project = personal.addProject({ name: 'Проверка', description: 'Личные данные', due: dateOffset(5) });
const card = personal.addCard({ text: 'Первая задача', project: project.id, due: dateOffset(1) });
assert.equal(personal.progress(project.id).percent, 0);
personal.moveCard(card.id, 'done');
assert.equal(personal.progress(project.id).percent, 100);
assert.equal(demo.data.cards.length, before, 'Demo must be isolated from personal data');
personal.moveCard(card.id, 'invalid');
assert.equal(personal.progress(project.id).percent, 100);
assert.throws(() => personal.addCard({ text: 'Task', project: 'unknown' }));
personal.deleteCard(card.id);
assert.equal(personal.progress(project.id).total, 0);
personal.addHabit('Читать');
const habit = personal.data.habits[0];
personal.toggleHabit(habit.id, dateOffset(1));
assert.equal(habit.days.length, 0, 'Future habit marks are disallowed');
personal.toggleHabit(habit.id, dateOffset(0));
assert.equal(habit.days.length, 1);
personal.toggleHabit(habit.id, dateOffset(0));
assert.equal(habit.days.length, 0);
const event = personal.addEvent({ text: 'Событие', time: '10:00', date: dateOffset(0), duration: 30 });
personal.toggleEvent(event.id);
assert.equal(event.done, true);
const restored = validateWorkspace(JSON.parse(JSON.stringify(personal.data)));
assert.equal(restored.projects[0].name, 'Проверка');
assert.equal(restored.schedule[0].done, true);
assert.equal(validateWorkspace({ projects: [null], cards: [null], habits: [null], schedule: [null] }).cards.length, 0);
console.log('OK: workspace isolation, project progress, invalid references, habits, schedules and restore validation.');
