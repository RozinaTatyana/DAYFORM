import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(fileURLToPath(import.meta.url));
const dist = path.join(root, 'dist');
const seen = new Set();
const modules = [];

async function collect(file) {
  const absolute = path.resolve(file);
  if (seen.has(absolute)) return;
  seen.add(absolute);
  const source = await readFile(absolute, 'utf8');
  const imports = [...source.matchAll(/^\s*import\s+\{([^}]+)\}\s+from\s+['"](.+)['"];?\s*$/gm)];
  for (const match of imports) await collect(path.resolve(path.dirname(absolute), match[2]));
  const aliases = imports.flatMap(match => match[1].split(',').map(part => part.trim()).filter(Boolean).flatMap(part => {
    const [original, alias] = part.split(/\s+as\s+/);
    return alias ? [`const ${alias.trim()} = ${original.trim()};`] : [];
  }));
  const body = source
    .replace(/^\s*import\s+\{[^}]+\}\s+from\s+['"].+['"];?\s*$/gm, '')
    .replace(/\bexport\s+(?=(class|function|const|let|var)\b)/g, '');
  modules.push(`// ${path.relative(root, absolute).replaceAll('\\', '/')}\n${aliases.join('\n')}\n${body}`);
}

await collect(path.join(dist, 'main.js'));
await writeFile(path.join(dist, 'dayform.standalone.js'), `/* Generated by build-standalone.mjs. Do not edit directly. */\n${modules.join('\n\n')}`, 'utf8');

const index = await readFile(path.join(dist, 'index.html'), 'utf8');
const standalone = index
  .replaceAll('href="styles/', 'href="dist/styles/')
  .replace('<strong>Открой DAYFORM через <code>start-dayform.cmd</code>.</strong><span>Этот файл использует модули JavaScript и не работает при прямом открытии <code>index.html</code>.</span>', '<strong>Загружаем DAYFORM…</strong><span>Если это сообщение не исчезает, включите JavaScript в браузере.</span>')
  .replace('<script type="module" src="main.js"></script>', '<script src="dist/dayform.standalone.js"></script>');
await writeFile(path.join(root, 'DAYFORM.html'), standalone, 'utf8');
await writeFile(path.join(dist, 'DAYFORM.html'), standalone
  .replaceAll('href="dist/styles/', 'href="styles/')
  .replace('src="dist/dayform.standalone.js"', 'src="dayform.standalone.js"'), 'utf8');
console.log(`Built standalone DAYFORM with ${modules.length} scripts.`);
