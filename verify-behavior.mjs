import assert from 'node:assert/strict';
import { APIWidget } from './dist/js/APIWidget.js';
import { FocusWidget } from './dist/js/FocusWidget.js';
import { WeatherWidget } from './dist/js/WeatherWidget.js';
import { AirWidget } from './dist/js/AirWidget.js';
const dashboard = { save() {}, announce() {}, recordSession(minutes) { this.recorded.push(minutes); }, recorded: [] };
const originalFetch = globalThis.fetch;
const pending = [];
globalThis.fetch = (url, options) => new Promise((resolve, reject) => pending.push({ resolve, reject, signal: options.signal }));
const widget = new APIWidget({title:'Test',type:'test'}, dashboard);
widget.output = { setAttribute() {} }; widget.url = () => 'https://example.invalid';
widget.showState = (text, state) => { widget.status = state; };
widget.hasData = data => Number.isFinite(data.value);
widget.showData = data => { widget.value = data.value; };
widget.output.dataset = {};
const first = widget.load(); assert.equal(widget.status, 'loading');
const second = widget.load(); assert.equal(pending[0].signal.aborted, true);
pending[1].resolve({ok:true,json:async()=>({value:2})}); await second;
pending[0].resolve({ok:true,json:async()=>({value:1})}); await first;
assert.equal(widget.value, 2, 'An old response must not overwrite a newer response');
const empty = widget.load(); pending[2].resolve({ok:true,json:async()=>({value:null})}); await empty; assert.equal(widget.status,'empty');
const failure = widget.load(); pending[3].resolve({ok:false}); await failure; assert.equal(widget.status,'error');
const active = widget.load(); widget.destroy(); assert.equal(pending[4].signal.aborted,true); assert.equal(widget.lifecycle.signal.aborted,true); pending[4].reject(new Error('aborted')); await active;
globalThis.fetch = originalFetch;
assert.equal(WeatherWidget.prototype.hasData({current:{temperature_2m:null}}),false);
assert.equal(AirWidget.prototype.hasData({current:{european_aqi:0}}),true);
const timer = new FocusWidget({type:'focus',state:{duration:15}},dashboard); timer.update = () => {}; timer.caption = {}; timer.running = true; timer.deadline = Date.now() - 1000;
timer.tick(); assert.deepEqual(dashboard.recorded,[15]); assert.equal(timer.running,false); assert.equal(timer.remaining,0);
timer.destroy(); assert.equal(timer.lifecycle.signal.aborted,true);
console.log('OK: stale request cancellation, empty/error states, destruction and completed focus recording.');
